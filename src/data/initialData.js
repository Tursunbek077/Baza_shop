export const getColorHex = (colorName) => {
  if (!colorName) return '#FAF7F2';
  const norm = (s) => s.toLowerCase().replace(/['`’‘]/g, '').trim();
  const target = norm(colorName);

  const found = BOUTIQUE_COLORS.find(c => norm(c.name) === target);
  if (found) return found.hex;

  if (target.includes('qora') || target.includes('black')) return '#1C1917';
  if (target.includes('oq') || target.includes('qaymoq') || target.includes('white')) return '#FAF7F2';
  if (target.includes('toq kok') || target.includes('navy')) return '#1B2A4A';
  if (target.includes('bardoviy') || target.includes('bordo') || target.includes('vino')) return '#781D2D';
  if (target.includes('pudra')) return '#E8B4B8';
  if (target.includes('pushti') || target.includes('pink') || target.includes('roz')) return '#F472B6';
  if (target.includes('sariq') || target.includes('lemon') || target.includes('yellow')) return '#FACC15';
  if (target.includes('zumrad')) return '#1B4D3E';
  if (target.includes('yashil') || target.includes('green')) return '#16A34A';
  if (target.includes('kulrang') || target.includes('seriy') || target.includes('gray') || target.includes('grey')) return '#6B7280';
  if (target.includes('moviy') || target.includes('kok') || target.includes('zangori') || target.includes('blue')) return '#89A8B2';
  if (target.includes('shokolad') || target.includes('jigar') || target.includes('brown')) return '#4A2E18';
  if (target.includes('bej') || target.includes('krem') || target.includes('beige')) return '#D7C4B7';
  return '#E5E7EB';
};
