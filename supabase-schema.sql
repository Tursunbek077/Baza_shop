-- BAZA_SHOP Supabase Database Schema

-- 1. Create Products Table
CREATE TABLE IF NOT EXISTS public.products (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL,
  price NUMERIC NOT NULL,
  old_price NUMERIC,
  sizes TEXT[] DEFAULT ARRAY['M', 'L']::TEXT[],
  colors TEXT[] DEFAULT ARRAY['Klassik Qora']::TEXT[],
  image TEXT,
  stock_status TEXT DEFAULT 'in_stock',
  is_sale BOOLEAN DEFAULT FALSE,
  is_banner_hero BOOLEAN DEFAULT FALSE,
  description TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Migration for existing installations:
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS colors TEXT[] DEFAULT ARRAY['Klassik Qora']::TEXT[];
ALTER TABLE public.products ADD COLUMN IF NOT EXISTS is_sale BOOLEAN DEFAULT FALSE;

-- 2. Create Banner Table
CREATE TABLE IF NOT EXISTS public.banner (
  id TEXT PRIMARY KEY DEFAULT 'main_banner',
  hero_product_id TEXT,
  tagline TEXT,
  headline TEXT,
  subheadline TEXT,
  badge_text TEXT,
  discount_badge TEXT,
  button_text TEXT,
  custom_image TEXT
);

-- 3. Create Orders Table
CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name TEXT,
  customer_phone TEXT NOT NULL,
  delivery_address TEXT,
  payment_method TEXT,
  items JSONB NOT NULL,
  total_amount NUMERIC NOT NULL,
  status TEXT DEFAULT 'yangi',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'yangi';

-- 4. Create Customers (Users) Table
CREATE TABLE IF NOT EXISTS public.customers (
  id TEXT PRIMARY KEY,
  phone TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  first_name TEXT NOT NULL,
  last_name TEXT,
  address TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Enable Row Level Security (RLS) & Public Policies for Baza_Shop
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.banner ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read products" ON public.products FOR SELECT USING (true);
CREATE POLICY "Allow public insert products" ON public.products FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update products" ON public.products FOR UPDATE USING (true);
CREATE POLICY "Allow public delete products" ON public.products FOR DELETE USING (true);

CREATE POLICY "Allow public read banner" ON public.banner FOR SELECT USING (true);
CREATE POLICY "Allow public insert banner" ON public.banner FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update banner" ON public.banner FOR UPDATE USING (true);

CREATE POLICY "Allow public read orders" ON public.orders FOR SELECT USING (true);
CREATE POLICY "Allow public insert orders" ON public.orders FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update orders" ON public.orders FOR UPDATE USING (true);

CREATE POLICY "Allow public read customers" ON public.customers FOR SELECT USING (true);
CREATE POLICY "Allow public insert customers" ON public.customers FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update customers" ON public.customers FOR UPDATE USING (true);

